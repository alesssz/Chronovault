/**
 * GET /sw.js — development only (registered under `$development` in
 * nuxt.config.ts): a service worker that removes itself.
 *
 * Why: a production build run on localhost (e.g. `make preview`) registers
 * the PWA service worker for http://localhost:3000. In development the PWA is
 * off and /sw.js does not exist, but the browser keeps fetching it to check
 * for updates: Nuxt rendered it as a page (router warning VUE_ROUTER_R0004)
 * and, as HTML, it could never replace the old worker, which kept running.
 *
 * Served here, this script is a valid update: the browser installs it, it
 * unregisters itself on activation and reloads the open tabs, so they run
 * without any service worker. Production builds serve the real /sw.js
 * generated by @vite-pwa/nuxt instead.
 */
const SELF_DESTROYING_WORKER = `
self.addEventListener('install', () => self.skipWaiting())
self.addEventListener('activate', () => {
  self.registration.unregister()
    .then(() => self.clients.matchAll({ type: 'window' }))
    .then((clients) => clients.forEach((client) => client.navigate(client.url)))
})
`

export default defineEventHandler((event) => {
  // A service worker script must be JavaScript, or the update is rejected;
  // never cached, so the browser always sees this version.
  setResponseHeaders(event, {
    'content-type': 'text/javascript; charset=utf-8',
    'cache-control': 'no-store',
  })
  return SELF_DESTROYING_WORKER
})
